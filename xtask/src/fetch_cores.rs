//! `cargo xtask fetch-cores`: download the upstream release kernels pinned in
//! `packaging/cores.toml`, verify them, and extract the bundle files.
//!
//! Each archive must match both the digest pinned in the repository and the
//! release's own `SHA256SUMS`. Only the kernel executable and the companions
//! listed for its target are extracted, by file name, into a fresh
//! `<version>` directory. The extracted files are then either checked against
//! `crates/etd-host/cores.lock` (the default) or written into it
//! (`--update-lock`, every target at once).

#[path = "../../crates/etd-host/core_lock.rs"]
#[allow(dead_code)]
mod core_lock;

use anyhow::{Context, Result, bail, ensure};
use serde::Deserialize;
use sha2::{Digest, Sha256};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::fs;
use std::io::Read;
use std::path::{Path, PathBuf};
use std::process::Command;

const PIN: &str = "packaging/cores.toml";
const LOCK: &str = "crates/etd-host/cores.lock";
const SUMS: &str = "SHA256SUMS";
const MAX_ARCHIVE: u64 = 256 << 20;
const MAX_MEMBER: u64 = 128 << 20;
const MAX_SUMS: u64 = 1 << 20;

/// The comment block every generated `cores.lock` starts with.
const LOCK_HEADER: &str = "\
# Release packaging supplies one executable row per bundle:
# Targets: x86_64/aarch64 for pc-windows-msvc, unknown-linux-gnu, apple-darwin.
# target-triple version lowercase-sha256
# Optional companion rows (before or after the executable row):
# target-triple version file:<plain-name> lowercase-sha256
# Names use ASCII letters, digits, dots, hyphens, underscores; no path,
# device name, leading/trailing dot, consecutive dots or executable name.
# Companion names are unique ignoring ASCII case; executable hashes are
# unique per target. Every file in the bundle directory must be listed.
# Only the current Rust target's entries are embedded in etd-host.
# An empty release table permits no kernels; no local manifest may add one.
#
# Generated by `cargo xtask fetch-cores --update-lock` from
# packaging/cores.toml; do not edit by hand.
";

#[derive(clap::Args, Debug)]
pub struct Args {
    /// Release tag to fetch; must be the tag pinned in packaging/cores.toml.
    #[arg(long)]
    release: Option<String>,
    /// Target triple to fetch, repeatable; `host` is this machine's.
    /// Default: every pinned target.
    #[arg(long = "target", value_name = "TRIPLE")]
    targets: Vec<String>,
    /// Output root; each target goes to <OUT>/<triple>/<version>/.
    /// Default: <target dir>/etd-cores.
    #[arg(long, value_name = "OUT", conflicts_with = "bundle")]
    out: Option<PathBuf>,
    /// Kernel directory beside a host image: the single selected target goes
    /// to <BUNDLE>/<version>/.
    #[arg(long, value_name = "BUNDLE")]
    bundle: Option<PathBuf>,
    /// Rewrite crates/etd-host/cores.lock from every pinned target.
    #[arg(long, conflicts_with_all = ["targets", "bundle"])]
    update_lock: bool,
    /// After verification, append <NAME>=<absolute kernel path> of the single
    /// selected target to the file named by $GITHUB_ENV (CI steps).
    #[arg(long, value_name = "NAME", conflicts_with = "update_lock")]
    github_env: Option<String>,
}

#[derive(Deserialize, Debug)]
#[serde(deny_unknown_fields)]
struct Pin {
    pub release: Release,
    pub target: Vec<Target>,
}

#[derive(Deserialize, Debug)]
#[serde(deny_unknown_fields)]
struct Release {
    pub repository: String,
    pub tag: String,
    pub commit: String,
    pub version: String,
}

#[derive(Deserialize, Debug)]
#[serde(deny_unknown_fields)]
struct Target {
    pub triple: String,
    pub archive: String,
    pub sha256: String,
    #[serde(default)]
    pub companions: Vec<String>,
}

impl Target {
    fn executable(&self) -> &'static str {
        if self.triple.contains("-windows-") {
            "easytier-core.exe"
        } else {
            "easytier-core"
        }
    }
}

/// SHA-256 of every extracted file, executable first.
#[derive(Debug, PartialEq, Eq)]
struct Extracted {
    exe: String,
    files: BTreeMap<String, String>,
}

fn is_plain(name: &str) -> bool {
    !name.is_empty()
        && !name.starts_with('.')
        && !name.contains("..")
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'-' | b'_'))
}

fn is_hex(value: &str, len: usize) -> bool {
    value.len() == len
        && value
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

fn parse_pin(text: &str) -> Result<Pin> {
    let pin: Pin = toml::from_str(text).with_context(|| format!("invalid {PIN}"))?;
    let release = &pin.release;
    let mut owner_repo = release.repository.split('/');
    ensure!(
        matches!(
            (owner_repo.next(), owner_repo.next(), owner_repo.next()),
            (Some(owner), Some(repo), None) if is_plain(owner) && is_plain(repo)
        ),
        "{PIN}: repository must be <owner>/<name>"
    );
    ensure!(is_plain(&release.tag), "{PIN}: invalid tag");
    ensure!(
        is_hex(&release.commit, 40),
        "{PIN}: commit must be a full hash"
    );
    ensure!(
        release.version.split('.').count() == 3
            && release
                .version
                .split('.')
                .all(|part| !part.is_empty() && part.bytes().all(|b| b.is_ascii_digit())),
        "{PIN}: version must be <major>.<minor>.<patch>"
    );
    ensure!(!pin.target.is_empty(), "{PIN}: no targets");
    let mut triples = BTreeSet::new();
    for target in &pin.target {
        ensure!(
            core_lock::supported_target(&target.triple),
            "{PIN}: unsupported target {}",
            target.triple
        );
        ensure!(
            triples.insert(target.triple.as_str()),
            "{PIN}: duplicate target {}",
            target.triple
        );
        ensure!(
            is_plain(&target.archive),
            "{PIN}: invalid archive name for {}",
            target.triple
        );
        ensure!(
            is_hex(&target.sha256, 64),
            "{PIN}: invalid archive digest for {}",
            target.triple
        );
        let mut names = BTreeSet::new();
        for name in &target.companions {
            ensure!(
                is_plain(name) && names.insert(name.to_ascii_lowercase()),
                "{PIN}: invalid or duplicate companion {name} for {}",
                target.triple
            );
        }
    }
    Ok(pin)
}

/// The triple of the machine this xtask runs on.
fn host_triple() -> Result<&'static str> {
    Ok(match (std::env::consts::ARCH, std::env::consts::OS) {
        ("x86_64", "windows") => "x86_64-pc-windows-msvc",
        ("aarch64", "windows") => "aarch64-pc-windows-msvc",
        ("x86_64", "linux") => "x86_64-unknown-linux-gnu",
        ("aarch64", "linux") => "aarch64-unknown-linux-gnu",
        ("x86_64", "macos") => "x86_64-apple-darwin",
        ("aarch64", "macos") => "aarch64-apple-darwin",
        (arch, os) => bail!("no release kernel for host {arch}-{os}"),
    })
}

/// `cores.lock` rows for one bundle, executable row first.
fn lock_rows(triple: &str, version: &str, bundle: &Extracted) -> String {
    let mut rows = format!("{triple} {version} {}\n", bundle.exe);
    for (name, hash) in &bundle.files {
        let _ = writeln!(rows, "{triple} {version} file:{name} {hash}");
    }
    rows
}

fn render_lock(pin: &Pin, bundles: &[(&Target, Extracted)]) -> String {
    let release = &pin.release;
    let mut text = format!(
        "{LOCK_HEADER}# Upstream {} {} ({}).\n",
        release.repository, release.tag, release.commit
    );
    for (target, bundle) in bundles {
        text.push('\n');
        text.push_str(&lock_rows(&target.triple, &release.version, bundle));
    }
    text
}

/// Digests by file name from a `sha256sum` listing.
fn parse_sums(text: &str) -> Result<BTreeMap<&str, &str>> {
    let mut sums = BTreeMap::new();
    for line in text.lines().map(str::trim).filter(|line| !line.is_empty()) {
        let (hash, name) = line
            .split_once(char::is_whitespace)
            .with_context(|| format!("malformed {SUMS} line: {line:?}"))?;
        let name = name.trim_start();
        let name = name.strip_prefix('*').unwrap_or(name);
        let hash = hash.trim();
        ensure!(is_hex(hash, 64), "malformed {SUMS} digest for {name}");
        ensure!(
            sums.insert(name, hash).is_none(),
            "duplicate {SUMS} entry for {name}"
        );
    }
    Ok(sums)
}

fn sha256(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .fold(String::with_capacity(64), |mut text, byte| {
            let _ = write!(text, "{byte:02x}");
            text
        })
}

fn download(url: &str, dest: &Path, limit: u64) -> Result<()> {
    let mut command = Command::new("curl");
    command
        .args([
            "--fail",
            "--location",
            "--silent",
            "--show-error",
            "--proto",
            "=https",
            "--proto-redir",
            "=https",
            "--connect-timeout",
            "30",
            "--retry",
            "3",
            "--max-filesize",
        ])
        .arg(limit.to_string())
        .arg("--output")
        .arg(dest)
        .arg(url)
        .stdin(std::process::Stdio::null());
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        command.creation_flags(0x0800_0000); // CREATE_NO_WINDOW
    }
    let status = command
        .status()
        .context("cannot run curl (needed to download release assets)")?;
    ensure!(status.success(), "downloading {url} failed: curl {status}");
    let size = fs::metadata(dest)?.len();
    ensure!(size <= limit, "{url} is larger than {limit} bytes");
    Ok(())
}

/// Extract the bundle members of one verified archive into `dest`, which
/// must not exist yet.
fn extract(archive: &Path, target: &Target, dest: &Path) -> Result<Extracted> {
    let exe = target.executable();
    let wanted: BTreeSet<&str> = std::iter::once(exe)
        .chain(target.companions.iter().map(String::as_str))
        .collect();
    let mut zip = zip::ZipArchive::new(fs::File::open(archive)?)
        .with_context(|| format!("{} is not a zip archive", archive.display()))?;
    let mut found = BTreeMap::new();
    for index in 0..zip.len() {
        let mut member = zip.by_index(index)?;
        if member.is_dir() {
            continue;
        }
        let Some(path) = member.enclosed_name() else {
            bail!("unsafe path in archive: {:?}", member.name());
        };
        let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
            continue;
        };
        let Some(&name) = wanted.get(name) else {
            continue;
        };
        ensure!(
            member.is_file() && !member.is_symlink(),
            "{name} in the archive is not a regular file"
        );
        ensure!(
            member.size() <= MAX_MEMBER,
            "{name} in the archive is too large"
        );
        let mut bytes = Vec::new();
        (&mut member).take(MAX_MEMBER + 1).read_to_end(&mut bytes)?;
        ensure!(
            bytes.len() as u64 <= MAX_MEMBER,
            "{name} in the archive is too large"
        );
        ensure!(
            found.insert(name, bytes).is_none(),
            "{name} appears twice in the archive"
        );
    }
    let present: BTreeSet<&str> = found.keys().copied().collect();
    let missing: Vec<&str> = wanted.difference(&present).copied().collect();
    ensure!(
        missing.is_empty(),
        "{} lacks {}",
        target.archive,
        missing.join(", ")
    );
    fs::create_dir_all(dest)?;
    let mut extracted = Extracted {
        exe: String::new(),
        files: BTreeMap::new(),
    };
    for (name, bytes) in found {
        let path = dest.join(name);
        fs::write(&path, &bytes).with_context(|| format!("cannot write {}", path.display()))?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = if name == exe { 0o755 } else { 0o644 };
            fs::set_permissions(&path, fs::Permissions::from_mode(mode))?;
        }
        let hash = sha256(&bytes);
        if name == exe {
            extracted.exe = hash;
        } else {
            extracted.files.insert(name.to_owned(), hash);
        }
    }
    Ok(extracted)
}

fn check_lock(lock: &str, triple: &str, version: &str, bundle: &Extracted) -> Result<()> {
    let table: core_lock::LockTable<'_> = core_lock::parse(lock).map_err(anyhow::Error::msg)?;
    let Some(row) = table.get(&(triple, version)) else {
        bail!("{LOCK} has no {triple} {version} rows; run `cargo xtask fetch-cores --update-lock`");
    };
    let files: BTreeMap<&str, &str> = bundle
        .files
        .iter()
        .map(|(name, hash)| (name.as_str(), hash.as_str()))
        .collect();
    ensure!(
        row.exe == Some(bundle.exe.as_str()) && row.files == files,
        "{triple} {version}: extracted files differ from {LOCK}:\n{}",
        lock_rows(triple, version, bundle)
    );
    Ok(())
}

pub fn run(root: &Path, args: Args) -> Result<()> {
    let pin = parse_pin(&fs::read_to_string(root.join(PIN)).context(PIN)?)?;
    let release = &pin.release;
    if let Some(tag) = &args.release {
        ensure!(
            *tag == release.tag,
            "{PIN} pins {}; edit it (archives and digests) to fetch {tag}",
            release.tag
        );
    }
    let mut selected = Vec::new();
    for requested in &args.targets {
        let triple = if requested == "host" {
            host_triple()?
        } else {
            requested.as_str()
        };
        let target = pin
            .target
            .iter()
            .find(|target| target.triple == triple)
            .with_context(|| format!("{PIN} pins no kernel for {triple}"))?;
        if !selected
            .iter()
            .any(|known: &&Target| known.triple == triple)
        {
            selected.push(target);
        }
    }
    if selected.is_empty() {
        selected = pin.target.iter().collect();
    }
    ensure!(
        (args.bundle.is_none() && args.github_env.is_none()) || selected.len() == 1,
        "--bundle and --github-env need exactly one --target"
    );
    if let Some(name) = &args.github_env {
        ensure!(
            !name.is_empty() && name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_'),
            "invalid --github-env name {name:?}"
        );
    }
    let target_dir = std::env::var_os("CARGO_TARGET_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| root.join("target"));
    let out = args.out.unwrap_or_else(|| target_dir.join("etd-cores"));
    let base = format!(
        "https://github.com/{}/releases/download/{}",
        release.repository, release.tag
    );

    let scratch = tempfile::tempdir()?;
    let sums_path = scratch.path().join(SUMS);
    download(&format!("{base}/{SUMS}"), &sums_path, MAX_SUMS)?;
    let sums_text = fs::read_to_string(&sums_path)?;
    let sums = parse_sums(&sums_text)?;

    let mut bundles = Vec::new();
    for target in selected {
        let published = sums
            .get(target.archive.as_str())
            .with_context(|| format!("{SUMS} of {} lists no {}", release.tag, target.archive))?;
        ensure!(
            *published == target.sha256,
            "{}: release {SUMS} says {published}, {PIN} pins {}",
            target.archive,
            target.sha256
        );
        let archive = scratch.path().join(&target.archive);
        download(&format!("{base}/{}", target.archive), &archive, MAX_ARCHIVE)?;
        let digest = sha256(&fs::read(&archive)?);
        ensure!(
            digest == target.sha256,
            "{}: downloaded digest {digest} differs from the pinned {}",
            target.archive,
            target.sha256
        );
        let dest = match &args.bundle {
            Some(bundle) => bundle.join(&release.version),
            None => out.join(&target.triple).join(&release.version),
        };
        if fs::symlink_metadata(&dest).is_ok() {
            fs::remove_dir_all(&dest)
                .with_context(|| format!("cannot replace {}", dest.display()))?;
        }
        let extracted = extract(&archive, target, &dest)?;
        fs::remove_file(&archive)?;
        let core = std::path::absolute(dest.join(target.executable()))?;
        println!("{} {}: {}", target.triple, release.version, core.display());
        bundles.push((target, extracted, core));
    }

    let lock_path = root.join(LOCK);
    if args.update_lock {
        let bundles: Vec<_> = bundles
            .into_iter()
            .map(|(target, extracted, _)| (target, extracted))
            .collect();
        let text = render_lock(&pin, &bundles);
        core_lock::parse(&text).map_err(anyhow::Error::msg)?;
        fs::write(&lock_path, text)?;
        println!("wrote {LOCK}");
    } else {
        let lock = fs::read_to_string(&lock_path).context(LOCK)?;
        for (target, bundle, _) in &bundles {
            check_lock(&lock, &target.triple, &release.version, bundle)?;
        }
        println!("extracted files match {LOCK}");
        if let (Some(name), [(_, _, core)]) = (&args.github_env, bundles.as_slice()) {
            let file = std::env::var_os("GITHUB_ENV").context("GITHUB_ENV is not set")?;
            let core = core.to_str().context("kernel path is not UTF-8")?;
            ensure!(!core.contains('\n'), "kernel path contains a newline");
            let mut env = fs::OpenOptions::new().append(true).open(file)?;
            std::io::Write::write_all(&mut env, format!("{name}={core}\n").as_bytes())?;
            println!("exported {name}");
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repository(path: &str) -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("..")
            .join(path)
    }

    fn bundle(exe: &str, files: &[(&str, &str)]) -> Extracted {
        Extracted {
            exe: exe.repeat(64),
            files: files
                .iter()
                .map(|(name, hash)| (name.to_string(), hash.repeat(64)))
                .collect(),
        }
    }

    #[test]
    fn committed_lock_covers_every_pinned_target() {
        let pin = parse_pin(&fs::read_to_string(repository(PIN)).unwrap()).unwrap();
        let lock = fs::read_to_string(repository(LOCK)).unwrap();
        assert!(lock.starts_with(LOCK_HEADER), "{LOCK} is not generated");
        let table = core_lock::parse(&lock).unwrap();
        let pinned: BTreeSet<_> = pin
            .target
            .iter()
            .map(|target| (target.triple.as_str(), pin.release.version.as_str()))
            .collect();
        assert_eq!(table.keys().copied().collect::<BTreeSet<_>>(), pinned);
        for target in &pin.target {
            let row = &table[&(target.triple.as_str(), pin.release.version.as_str())];
            assert_eq!(
                row.files.keys().copied().collect::<BTreeSet<_>>(),
                target.companions.iter().map(String::as_str).collect(),
                "{}",
                target.triple
            );
        }
    }

    #[test]
    fn rendered_lock_is_accepted_and_checked() {
        let pin = parse_pin(&fs::read_to_string(repository(PIN)).unwrap()).unwrap();
        let windows = &pin.target[0];
        let ok = bundle("a", &[("Packet.dll", "b"), ("wintun.dll", "c")]);
        let text = render_lock(
            &pin,
            &[(
                windows,
                bundle("a", &[("Packet.dll", "b"), ("wintun.dll", "c")]),
            )],
        );
        core_lock::parse(&text).unwrap();
        let version = &pin.release.version;
        check_lock(&text, &windows.triple, version, &ok).unwrap();
        let tampered = bundle("a", &[("Packet.dll", "d"), ("wintun.dll", "c")]);
        assert!(check_lock(&text, &windows.triple, version, &tampered).is_err());
        let extra = bundle(
            "a",
            &[("Packet.dll", "b"), ("wintun.dll", "c"), ("x.dll", "e")],
        );
        assert!(check_lock(&text, &windows.triple, version, &extra).is_err());
        assert!(check_lock(&text, "x86_64-unknown-linux-gnu", version, &ok).is_err());
    }

    #[test]
    fn pin_rejects_unsafe_values() {
        let good = fs::read_to_string(repository(PIN)).unwrap();
        for (from, to) in [
            ("tag = \"v2.7.1\"", "tag = \"../v2.7.1\""),
            ("easytier-linux-x86_64-v2.7.1.zip", "../x.zip"),
            ("\"wintun.dll\"]", "\"wintun.dll\", \"WINTUN.DLL\"]"),
            ("\"wintun.dll\"]", "\"sub/wintun.dll\"]"),
            (
                "triple = \"x86_64-apple-darwin\"",
                "triple = \"x86_64-unknown-freebsd\"",
            ),
            ("commit = \"0d9c52b1", "commit = \""),
        ] {
            assert!(good.contains(from), "{from}");
            assert!(parse_pin(&good.replacen(from, to, 1)).is_err(), "{to}");
        }
    }

    #[test]
    fn sums_parse_both_listing_forms() {
        let listing = format!("{}  a.zip\n{} *b.zip\n", "1".repeat(64), "2".repeat(64));
        let sums = parse_sums(&listing).unwrap();
        assert_eq!(sums["a.zip"], "1".repeat(64));
        assert_eq!(sums["b.zip"], "2".repeat(64));
        assert!(parse_sums("abc  a.zip").is_err());
    }

    #[test]
    fn extracts_only_listed_members() {
        use std::io::Write;
        let dir = tempfile::tempdir().unwrap();
        let archive = dir.path().join("a.zip");
        let mut writer = zip::ZipWriter::new(fs::File::create(&archive).unwrap());
        let options = zip::write::SimpleFileOptions::default()
            .compression_method(zip::CompressionMethod::Stored);
        for (name, body) in [
            ("easytier-linux-x86_64/easytier-core", "core"),
            ("easytier-linux-x86_64/easytier-cli", "cli"),
            ("easytier-linux-x86_64/lib.so", "lib"),
        ] {
            writer.start_file(name, options).unwrap();
            writer.write_all(body.as_bytes()).unwrap();
        }
        writer.finish().unwrap();
        let target = Target {
            triple: "x86_64-unknown-linux-gnu".into(),
            archive: "a.zip".into(),
            sha256: "0".repeat(64),
            companions: vec!["lib.so".into()],
        };
        let dest = dir.path().join("out");
        let extracted = extract(&archive, &target, &dest).unwrap();
        assert_eq!(extracted.exe, sha256(b"core"));
        assert_eq!(extracted.files["lib.so"], sha256(b"lib"));
        let mut names: Vec<_> = fs::read_dir(&dest)
            .unwrap()
            .map(|entry| entry.unwrap().file_name().into_string().unwrap())
            .collect();
        names.sort();
        assert_eq!(names, ["easytier-core", "lib.so"]);
        let missing = Target {
            companions: vec!["absent.dll".into()],
            ..target
        };
        assert!(extract(&archive, &missing, &dir.path().join("out2")).is_err());
    }
}
