//! Method to role table, read from the compiled descriptor so the
//! `(etd.v1.required_role)` option in the `.proto` file is the only source.
use crate::{FILE_DESCRIPTOR_SET, Role};
use prost::Message;
use std::sync::LazyLock;

/// The role a contract method requires.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MethodRole {
    /// gRPC path, e.g. `/etd.v1.HostService/Apply`.
    pub path: String,
    /// `None` when the method lacks the option; hosts must reject such calls.
    pub role: Option<Role>,
    pub client_streaming: bool,
    pub server_streaming: bool,
}

/// Every method of every service in the contract.
pub fn method_roles() -> &'static [MethodRole] {
    static TABLE: LazyLock<Vec<MethodRole>> = LazyLock::new(|| {
        let set = FileDescriptorSet::decode(FILE_DESCRIPTOR_SET)
            .expect("embedded descriptor set is generated by prost-build");
        let mut table = Vec::new();
        for file in set.file {
            for service in file.service {
                for method in service.method {
                    let role = method
                        .options
                        .and_then(|options| options.required_role)
                        .and_then(|value| Role::try_from(value).ok())
                        .filter(|role| *role != Role::Unspecified);
                    table.push(MethodRole {
                        path: format!("/{}.{}/{}", file.package, service.name, method.name),
                        role,
                        client_streaming: method.client_streaming,
                        server_streaming: method.server_streaming,
                    });
                }
            }
        }
        table
    });
    &TABLE
}

/// Role required by the method at `path` (`/package.Service/Method`); `None`
/// for unknown methods and methods without the option.
pub fn required_role(path: &str) -> Option<Role> {
    method_roles()
        .iter()
        .find(|entry| entry.path == path)
        .and_then(|entry| entry.role)
}

// Minimal mirror of google/protobuf/descriptor.proto: only the fields needed
// to read method options, including the custom extension field, which
// prost-types would drop as unknown.
#[derive(Clone, PartialEq, Message)]
struct FileDescriptorSet {
    #[prost(message, repeated, tag = "1")]
    file: Vec<FileDescriptorProto>,
}
#[derive(Clone, PartialEq, Message)]
struct FileDescriptorProto {
    #[prost(string, tag = "2")]
    package: String,
    #[prost(message, repeated, tag = "6")]
    service: Vec<ServiceDescriptorProto>,
}
#[derive(Clone, PartialEq, Message)]
struct ServiceDescriptorProto {
    #[prost(string, tag = "1")]
    name: String,
    #[prost(message, repeated, tag = "2")]
    method: Vec<MethodDescriptorProto>,
}
#[derive(Clone, PartialEq, Message)]
struct MethodDescriptorProto {
    #[prost(string, tag = "1")]
    name: String,
    #[prost(message, optional, tag = "4")]
    options: Option<MethodOptions>,
    #[prost(bool, tag = "5")]
    client_streaming: bool,
    #[prost(bool, tag = "6")]
    server_streaming: bool,
}
#[derive(Clone, PartialEq, Message)]
struct MethodOptions {
    /// `(etd.v1.required_role)`; must equal [`crate::REQUIRED_ROLE_OPTION`].
    #[prost(enumeration = "Role", optional, tag = "50000")]
    required_role: Option<i32>,
}
